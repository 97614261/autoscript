[CmdletBinding()]
param([switch]$Update)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repo = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$target = Join-Path $repo 'docs/reference/studio-block-coverage.md'
$compiler = Get-Content -LiteralPath (Join-Path $repo 'rust/tools/flow-compiler/src/lib.rs') -Raw -Encoding UTF8
$compiler = [regex]::Match($compiler, '(?s)pub const SUPPORTED_NODE_VERSIONS:.*?=\s*&\[(.*?)\];').Groups[1].Value
if (-not $compiler) { throw 'Missing explicit compiler registry' }
$registered = @{}
foreach ($match in [regex]::Matches($compiler, 'SupportedNodeVersion\s*\{\s*kind:\s*"([^"]+)"\s*,\s*version:\s*(\d+)')) {
    $key = $match.Groups[1].Value
    $version = [int]$match.Groups[2].Value
    if (-not $registered.ContainsKey($key)) { $registered[$key] = @() }
    if ($version -in $registered[$key]) { throw "Duplicate compiler registration: $key v$version" }
    $registered[$key] += $version
}
$blocks = @(Get-ChildItem -LiteralPath (Join-Path $repo 'schema/block-catalog/blocks') -Filter '*.json' -File | ForEach-Object {
    Get-Content -LiteralPath $_.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
} | Sort-Object kind)
$schemas = @{}
Get-ChildItem -LiteralPath (Join-Path $repo 'schema/node-schema') -Filter '*.json' -File | ForEach-Object {
    $node = Get-Content -LiteralPath $_.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($node.PSObject.Properties['$id']) {
        if ($schemas.ContainsKey($node.'$id')) { throw 'Duplicate node schema identity' }
        $schemas[$node.'$id'] = @{ Name = $_.Name; Node = $node }
    }
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# Studio published-block coverage')
$lines.Add('')
$lines.Add('Generated by scripts/audit-studio-functions.ps1 -Update. Run without -Update for a read-only consistency check.')
$lines.Add('')
$lines.Add("Published blocks: $($blocks.Count). Compiler registrations: $($registered.Count).")
$lines.Add('')
$lines.Add('Evidence: every row has a matching node schema and exact compiler kind/version. All rows enter the generated FunctionCatalog, shared VisualNodeArgumentsDialog dispatcher (specialized or contract-driven), VisualEditorState save validation and the reversible source toolchain. These are source-path facts, not executed runtime/parameter/device acceptance.')
$lines.Add('')
$lines.Add('Shared paths: [catalog](../../android/apps/studio-android/src/main/java/com/autoscript/studio/editor/FunctionCatalog.kt), [configuration](../../android/apps/studio-android/src/main/java/com/autoscript/studio/editor/VisualBlockArguments.kt), [editor](../../android/apps/studio-android/src/main/java/com/autoscript/studio/editor/VisualEditorState.kt), [compiler](../../rust/tools/flow-compiler/src/lib.rs), [catalog regression](../../android/apps/studio-android/src/test/java/com/autoscript/studio/editor/FunctionLibraryTest.kt), [source roundtrip regression](../../android/apps/studio-android/src/test/java/com/autoscript/studio/editor/VisualLuaRoundTripTest.kt), [audited production routes and retired gaps](studio-first-version-master-plan.md).')
$lines.Add('')
$lines.Add('Runtime: variable/control/flow blocks compile to structured Lua; other blocks dispatch through the frozen runtime contract. Host requests are serviced by runtime-service, pure operations by runtime-executor. The table does not infer API equivalence from names. Current regression execution and device acceptance remain PENDING for every row; historical batch evidence stays in its original verification record.')
$lines.Add('')
$lines.Add('| Kind | Title | Version | Schema / Compiler | Capabilities | Runtime / Device Acceptance |')
$lines.Add('|---|---|---:|---|---|---|')
$seen = @{}
foreach ($block in $blocks) {
    $kind = $block.kind
    if ($seen.ContainsKey($kind)) { throw "Duplicate published kind: $kind" }
    $seen[$kind] = $true
    if (-not $registered.ContainsKey($kind) -or $block.nodeVersion -notin $registered[$kind]) { throw "Compiler kind/version mismatch: $kind" }
    if (-not $schemas.ContainsKey($block.nodeSchemaId)) { throw "Missing node schema: $kind" }
    $schema = $schemas[$block.nodeSchemaId]
    if ($schema.Node.properties.kind.const -ne $kind -or $schema.Node.properties.nodeVersion.const -ne $block.nodeVersion) {
        throw "Node schema kind/version mismatch: $kind"
    }
    $title = $block.title.Replace('|','/').Replace("`r",' ').Replace("`n",' ')
    $caps = if (@($block.requiredCapabilities).Count) { @($block.requiredCapabilities) -join ', ' } else { '-' }
    $nodeLink = '../../schema/node-schema/' + $schema.Name
    $lines.Add('| `' + $kind + '` | ' + $title + ' | ' + $block.nodeVersion + ' | [schema](' + $nodeLink + ') / registered | ' + $caps + ' | PENDING / PENDING |')
}
if ($registered.Count -ne $seen.Count) { throw 'Unpublished compiler registrations require explicit review' }
$expected = ($lines -join "`n") + "`n"
if ($Update) {
    [IO.File]::WriteAllText($target, $expected, [Text.UTF8Encoding]::new($false))
} else {
    if (-not (Test-Path -LiteralPath $target) -or (Get-Content -LiteralPath $target -Raw -Encoding UTF8).Replace("`r`n","`n") -ne $expected) {
        throw 'Studio coverage matrix is stale; run scripts/audit-studio-functions.ps1 -Update'
    }
}
Write-Output "Studio coverage: $($blocks.Count) published kinds, exact schema/compiler registrations; runtime/device gates remain pending."
