fn value_source_project() -> ProjectManifest {
    let mut project = manifest(
        json!([
            {"name":"s","scope":"global","type":"string"},
            {"name":"n","scope":"flow","flowId":"main","type":"integer"},
            {"name":"out","scope":"flow","flowId":"main","type":"string"},
            {"name":"foreign","scope":"flow","flowId":"child","type":"integer"},
            {"name":"frame","scope":"global","type":"image"}
        ]),
        json!([]),
    );
    project.runtime_api = "1.8".into();
    project.capabilities.push("core.text".into());
    project
}

#[test]
fn value_source_loops_convert_and_read_current_values_without_extra_nodes() {
    let project = value_source_project();
    let nodes = [
        node("variable.set", json!({"name":"s","value":"+2"})),
        loop_node(
            "repeat",
            None,
            "block-main",
            0,
            "control.repeat",
            json!({"times":0,"timesVariable":"=int(s)+1"}),
            Some("body"),
        ),
        loop_node(
            "inc",
            Some("repeat"),
            "body",
            1,
            "variable.calculate",
            json!({"name":"n","expression":"n+1"}),
            None,
        ),
        loop_node(
            "sleep",
            Some("repeat"),
            "body",
            1,
            "task.sleep",
            json!({"milliseconds":0,"millisecondsVariable":"=n*10"}),
            None,
        ),
        loop_node(
            "while",
            None,
            "block-main",
            0,
            "control.while",
            json!({"variable":"=n+1","operator":"lessThan","value":6,"maxIterations":10}),
            Some("while-body"),
        ),
        loop_node(
            "while-inc",
            Some("while"),
            "while-body",
            1,
            "variable.calculate",
            json!({"name":"n","expression":"n+1"}),
            None,
        ),
        log("n"),
    ];
    let bundle = sources(&project, &nodes, &[]);
    let lua = execute_loop_bundle(&bundle);
    assert_eq!(loop_logs(&lua), ["5"]);
    assert_eq!(lua.globals().get::<i64>("clock").unwrap(), 60);
    assert!(bundle
        .main_lua
        .starts_with(b"-- @generated by flow-compiler; do not edit.\n-- generationId:"));
    assert!(!String::from_utf8_lossy(&bundle.main_lua).contains("load("));
}

