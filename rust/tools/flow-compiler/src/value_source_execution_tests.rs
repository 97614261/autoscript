#[test]
fn value_source_real_utility_data_copy_and_output_use_the_same_expression_engine() {
    let project = value_source_project();
    let bundle = sources(
        &project,
        &[
            node("variable.set", json!({"name":"s","value":"+190"})),
            node(
                "text.length",
                json!({"text":"","textVariable":"=text(int(s))","resultVariable":"n"}),
            ),
            log("n"),
            node(
                "data.length",
                json!({"json":"[]","jsonVariable":"=split(\"100,+100,180\",\",\")","resultVariable":"n"}),
            ),
            log("n"),
            node(
                "variable.copy",
                json!({"name":"n","sourceName":"=itemInt(split(\"100,+100,180\",\",\"),2)"}),
            ),
            node(
                "task.log",
                json!({"level":"info","message":"value","valueVariable":"=text(n)..\":\"..text(180)"}),
            ),
        ],
        &[],
    );
    assert_eq!(
        run_quick_calculation_bundle(&bundle)
            .unwrap()
            .iter()
            .map(|s| s.strip_prefix("脚本/INFO: ").unwrap_or(s).to_string())
            .collect::<Vec<_>>(),
        ["3", "3", "100:180"]
    );
}

fn value_source_rejection(project: &ProjectManifest, operation: Value) -> Vec<crate::CompileError> {
    let mut operation = operation;
    let map = operation.as_object_mut().unwrap();
    for (key, value) in json!({"flowSchemaVersion":1,"nodeId":"bad","blockId":"block-main","parentId":null,"orderKey":"a0","nodeVersion":1,"depth":0}).as_object().unwrap() {
        map.entry(key.clone()).or_insert(value.clone());
    }
    let text = format!("{operation}\n");
    let options = LoadOptions {
        flow_id: "main",
        root_block_id: "block-main",
        flow_schema_version: 1,
        supported_nodes: SUPPORTED_NODE_VERSIONS,
    };
    let main = load_jsonl(text.as_bytes(), options);
    let child = load_jsonl(
        b"",
        LoadOptions {
            flow_id: "child",
            root_block_id: "block-child",
            ..options
        },
    );
    compile_project(
        project,
        &[
            FlowSource {
                flow_id: "main",
                exact_bytes: text.as_bytes(),
                report: &main,
            },
            FlowSource {
                flow_id: "child",
                exact_bytes: b"",
                report: &child,
            },
        ],
    )
    .unwrap_err()
}

#[test]
fn value_source_rejects_wrong_types_scope_image_handles_destinations_and_source_code() {
    let project = value_source_project();
    for source in [
        "=s",
        "=frame",
        "=foreign",
        "=n/2",
        "=1; os.execute(\"x\")",
        "=unknown(1)",
    ] {
        let errors = value_source_rejection(
            &project,
            json!({"kind":"control.repeat","childBlocks":{"body":"empty-body"},"args":{"times":0,"timesVariable":source}}),
        );
        assert!(errors.iter().any(|e| matches!(e, crate::CompileError::InvalidNodeArguments {node_id,..} if node_id=="bad")), "{source}: {errors:?}");
    }
    for operation in [
        node("text.length", json!({"text":"abc","resultVariable":"=1"})),
        node("clipboard.gettext", json!({"resultVariable":"=text(1)"})),
        node("screen.release", json!({"name":"=1"})),
    ] {
        assert!(!value_source_rejection(&project, operation).is_empty());
    }
    let mut old = project.clone();
    old.runtime_api = "1.7".into();
    assert!(value_source_rejection(
        &old,
        node(
            "task.sleep",
            json!({"milliseconds":0,"millisecondsVariable":"=1"})
        )
    )
    .iter()
    .any(|e| format!("{e:?}").contains("1.8")));
}

