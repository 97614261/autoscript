#[test]
fn value_source_mapped_coordinates_evaluate_conversions_without_changing_handles() {
    let mut project = value_source_project();
    project.capabilities.push("screen.capture".into());
    let args = json!({"frameVariable":"frame","x":0,"y":0,"xVariable":"=int(s)+1","yVariable":"=n*2","resultVariable":"out"});
    let bundle = sources(
        &project,
        &[
            node("variable.set", json!({"name":"s","value":"+190"})),
            node("variable.set", json!({"name":"n","value":3})),
            node("screen.mappoint", args.clone()),
            log("out"),
        ],
        &[],
    );
    let lua = runtime();
    lua.load("Screen={mapPoint=function(frame,x,y) return tostring(x)..','..tostring(y) end}")
        .exec()
        .unwrap();
    lua.load(&bundle.main_lua)
        .eval::<mlua::Function>()
        .unwrap()
        .call::<()>(())
        .unwrap();
    assert_eq!(loop_logs(&lua), ["191,6"]);
    for (key, source) in [
        ("frameVariable", "=1"),
        ("resultVariable", "=text(n)"),
        ("xVariable", "=text(n)"),
    ] {
        let mut invalid = args.clone();
        invalid[key] = json!(source);
        assert!(!value_source_rejection(&project, node("screen.mappoint", invalid)).is_empty());
    }
}
