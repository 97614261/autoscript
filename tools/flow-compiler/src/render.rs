fn render_comparison(arguments: &crate::analyze::ComparisonArgs) -> Result<String, CompileError> {
    comparison_expression(
        &arguments.variable,
        arguments.operator,
        &arguments.value,
        arguments.value_variable.as_deref(),
    )
}

fn render_while_comparison(arguments: &crate::analyze::WhileArgs) -> Result<String, CompileError> {
    comparison_expression(
        &arguments.variable,
        arguments.operator,
        &arguments.value,
        None,
    )
}

fn comparison_expression(
    variable: &str,
    operator: ComparisonOperator,
    value: &Value,
    value_variable: Option<&str>,
) -> Result<String, CompileError> {
    let right = match value_variable {
        Some(name) => format!("__vars[{}]", lua_string(name)?),
        None => lua_literal(value)?,
    };
    Ok(format!(
        "__compare(__vars[{}],{}, {})",
        lua_string(variable)?,
        lua_string(comparison_operator(operator))?,
        right
    ))
}

const fn comparison_operator(operator: ComparisonOperator) -> &'static str {
    match operator {
        ComparisonOperator::Equals => "equals",
        ComparisonOperator::NotEquals => "notEquals",
        ComparisonOperator::LessThan => "lessThan",
        ComparisonOperator::LessOrEqual => "lessOrEqual",
        ComparisonOperator::GreaterThan => "greaterThan",
        ComparisonOperator::GreaterOrEqual => "greaterOrEqual",
    }
}

