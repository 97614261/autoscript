fn render_find_image(
    value: &crate::analyze::FindImageArgs,
    key: &str,
    numeric_found: bool,
) -> Result<String, CompileError> {
    let found_expression = if numeric_found {
        "__point and 1 or 0"
    } else {
        "__point ~= nil"
    };
    let region = &value.region;
    let edges = [region.left, region.top, region.right, region.bottom];
    let region_expressions = value
        .region_variables()
        .iter()
        .zip(edges)
        .map(|(variable, literal)| {
            variable.map_or_else(
                || Ok(literal.to_string()),
                |name| Ok(format!("__vars[{}]", lua_string(name)?)),
            )
        })
        .collect::<Result<Vec<String>, CompileError>>()?;
    let direction = if value.has_extended_options() {
        format!(",{}", value.direction)
    } else {
        String::new()
    };
    if value.has_extended_options() {
        let paths = if value.image_paths.is_empty() {
            vec![value.image_path.clone()]
        } else {
            value.image_paths.clone()
        };
        let paths_json = serde_json::to_string(&paths)
            .map_err(|error| CompileError::Serialization(error.to_string()))?;
        let frame = if value.auto_capture {
            "Screen.cache(Screen.capture())".to_owned()
        } else {
            format!("__vars[{}]", lua_string(&value.frame_variable)?)
        };
        let mut result = format!(
            "do local __recognize = __recognition_visit({}, {});",
            lua_string(key)?,
            value.frequency,
        );
        if let Some(name) = &value.image_variable {
            let variable = lua_string(name)?;
            result.push_str(&format!(" if __vars[{variable}] then Screen.release(__vars[{variable}]); __vars[{variable}] = nil end;"));
        }
        result.push_str(&format!(
            " local __point; if __recognize then local __frame = {frame}; __point = Screen.findImages(__frame,{},{},{},{},{},{},{},{});",
            lua_string(&paths_json)?, value.tolerance, value.similarity_permille,
            region_expressions[0],region_expressions[1],region_expressions[2],region_expressions[3],value.direction,
        ));
        if let Some(name) = &value.image_variable {
            result.push_str(&format!(" if __point then __vars[{}] = Screen.crop(__frame,__point.x,__point.y,__point.x+__point.width,__point.y+__point.height) end;",lua_string(name)?));
        }
        if value.auto_capture {
            result.push_str(" Screen.release(__frame);");
        }
        result.push_str(&format!(" end; __vars[{}] = {found_expression}; __vars[{}] = __point and __point.x or nil; __vars[{}] = __point and __point.y or nil;",
            lua_string(&value.found_variable)?,lua_string(&value.x_variable)?,lua_string(&value.y_variable)?,
        ));
        for (name, field) in [
            (value.template_variable.as_deref(), "path"),
            (value.score_variable.as_deref(), "scorePermille"),
        ] {
            if let Some(name) = name {
                result.push_str(&format!(
                    " __vars[{}] = __point and __point.{field} or nil;",
                    lua_string(name)?
                ));
            }
        }
        if value.success_action != crate::analyze::RecognitionAction::None {
            use crate::analyze::RecognitionAction;
            result.push_str(&format!(
                " if __point then local __x,__y=__point.x+({}),__point.y+({});",
                value.offset_x, value.offset_y
            ));
            match value.success_action {
                RecognitionAction::Tap => result.push_str(" Input.tapScreen(__x,__y);"),
                RecognitionAction::Hold => result.push_str(" Input.pointerDownScreen(__x,__y);"),
                RecognitionAction::TapWait => result.push_str(&format!(
                    " Input.tapScreen(__x,__y); Task.sleep({});",
                    value.action_duration_ms
                )),
                RecognitionAction::PressRelease => result.push_str(&format!(
                    " Input.pointerDownScreen(__x,__y); Task.sleep({}); Input.pointerUp();",
                    value.action_duration_ms
                )),
                RecognitionAction::None => {}
            }
            result.push_str(" end;");
        }
        result.push_str(" end");
        return Ok(result);
    }
    Ok(format!(
        "do local __template = Screen.loadImage({}); local __point = Screen.findImage(__vars[{}],__template,{},{},{},{},{},{}{}); Screen.release(__template); __vars[{}] = {found_expression}; __vars[{}] = __point and __point.x or nil; __vars[{}] = __point and __point.y or nil end",
        lua_string(&value.image_path)?,
        lua_string(&value.frame_variable)?,
        value.tolerance,
        value.similarity_permille,
        region_expressions[0],
        region_expressions[1],
        region_expressions[2],
        region_expressions[3],
        direction,
        lua_string(&value.found_variable)?,
        lua_string(&value.x_variable)?,
        lua_string(&value.y_variable)?,
    ))
}

